"""Bundle pinned, offline SVG themes from development-only npm packages.

Run after updating their versions. The generated manifest only references files
we ship; neither repository filenames nor provider names become asset URLs.
"""
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT / "dikdik/web"


def main():
    theme = ROOT / "node_modules/material-icon-theme"
    manifest = json.loads((theme / "dist/material-icons.json").read_text(encoding="utf-8"))
    target = WEB / "assets/files"
    target.mkdir(parents=True, exist_ok=True)
    definitions = {}
    for key, definition in manifest.pop("iconDefinitions").items():
        name = Path(definition["iconPath"]).name
        source = theme / "icons" / name
        if source.is_file() and name.endswith(".svg"):
            shutil.copyfile(source, target / name)
            definitions[key] = name
    manifest["icons"] = definitions
    # Compact maps preserve all filename, compound extension and folder associations.
    output = "// Generated by scripts/bundle_editor_assets.py. See assets/NOTICES.md.\n"
    output += "export const fileTheme = " + json.dumps(manifest, ensure_ascii=False, separators=(",", ":")) + ";\n"
    (WEB / "icon-manifest.ts").write_text(output, encoding="utf-8", newline="\n")
    shutil.copyfile(theme / "LICENSE", WEB / "assets/LICENSE-material-icon-theme.txt")
    shutil.copyfile(ROOT / "node_modules/highlight.js/LICENSE", WEB / "assets/LICENSE-highlight.js.txt")
    providers = WEB / "assets/providers"
    providers.mkdir(parents=True, exist_ok=True)
    names = "openrouter openai anthropic gemini-color deepseek-color grok mistral-color groq cerebras-color together-color fireworks-color moonshot zai qwen-color perplexity-color ollama lmstudio azure-color".split()
    for name in names:
        shutil.copyfile(ROOT / "node_modules/@lobehub/icons-static-svg/icons" / (name + ".svg"), providers / (name + ".svg"))
    print(f"Bundled {len(definitions)} file/folder symbols and {len(names)} provider logos.")


if __name__ == "__main__":
    main()
